package Spark3;
public class OpeDemo {
        public static void main(String[] args)
        {
            int a=10;
            int b=2;
            System.out.println(a+b); //addition
            System.out.println(a-b);
            System.out.println(a*b);
            System.out.println(a/b);
            System.out.println(a%b); //modulo

            System.out.println(2/4);
            System.out.println(2%4);
            System.out.println(2/0.5);
        }

}
